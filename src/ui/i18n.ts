let registered = false

export function initI18n() {
	if (registered) return
	registered = true
	try {
		if ((globalThis as any).Language?.code === 'zh') {
			;(globalThis as any).Language.addTranslations('zh', prefixKeys(ZH))
		}
	} catch (err) {
		console.warn('behemiron_jolt: failed to register zh translations', err)
	}
}

function prefixKeys(table: Record<string, string>): Record<string, string> {
	const out: Record<string, string> = {}
	for (const [key, value] of Object.entries(table)) out['behemiron_jolt.' + key] = value
	return out
}

// t('panel.friction') / t('panel.body', name) — vars map to %0, %1 …
export function t(key: string, ...vars: (string | number)[]): string {
	let def = EN[key]
	if (def === undefined) {
		console.warn('[behemiron_jolt] missing i18n key:', key)
		def = key
	}
	const full = 'behemiron_jolt.' + key
	let s: string
	try {
		s = (globalThis as any).tl(full, vars.length ? vars : undefined, def)
	} catch {
		s = def
	}
	if (s === full) s = def
	// tl only substitutes when it finds a registered translation; the default_value path
	// (English users) comes back raw — substitute either way.
	for (let i = 0; i < vars.length; i++) {
		s = s.split('%' + i).join(String(vars[i]))
	}
	return s
}

